const event={time:3,intensity:100,radius:180,duration:90};
const constantAir=(x=20,y=0,z=0)=>({center:()=>({x:0,z:0}),envelope:()=>1,terrain:()=>0,waterAt:()=>0,sample:(_x,_y,_z,out={})=>Object.assign(out,{wx:x,wy:y,wz:z,ux:0,uz:0,height:0})});
function single(diameter,field=constantAir()){
 const model=new TornadoParticles(field,{dust:1,flecks:0,turbulence:false});model.update(0,event);
 const p=model.dust[0];p.p={x:10,y:100,z:0};p.v={x:0,y:0,z:0};p.age=0;p.life=100;p.diameter=diameter;p.density=2600;
 return {model,p};
}
test('Actual dust parcels respond to grain diameter independently of their visible puff size',()=>{
 const fine=single(20e-6),coarse=single(1.5e-3);
 for(let i=0;i<6;i++){fine.model.update(1/60,event);coarse.model.update(1/60,event);}
 assert.ok(fine.p.v.x>19,'fine grains must closely follow a 20 m/s air stream');
 assert.ok(coarse.p.v.x<8,'coarse grains must retain inertia over the same first tenth second');
 assert.ok(fine.p.p.x>coarse.p.p.x+1,'size-dependent response must affect actual world positions');
});

const grain=(diameter=10e-6,density=2600)=>({diameter,density,p:{x:0,y:100,z:0},v:{x:0,y:0,z:0}});
test('Fine grains settle at the analytical Stokes limit with gravity coupled to drag',()=>{
 const p=grain(),still={x:0,y:0,z:0};
 const tau=.000798035605,terminal=.007825040746;
 for(let i=0;i<120;i++)advanceAerosol(p,still,1/60);
 // Finite-Re correction is 0.407% at this diameter. A separate gravity kick
 // would give 0.1635 m/s, over twenty times the analytical settling speed.
 assert.ok(Math.abs(-p.v.y-terminal)/terminal<.006);
 assert.ok(Math.abs((100-p.p.y)-terminal*(2-tau))<.00012);
 assert.equal(p.v.x,0);assert.equal(p.v.z,0);
 assert.ok(Math.abs(p.grainMass-1.36135681656e-12)<1e-22);
});

test('Creeping-flow relaxation follows analytical velocity and displacement',()=>{
 const p=grain(),u=.001,t=.003,tau=.000798035605;
 for(let i=0;i<30;i++)advanceAerosol(p,{x:u,y:0,z:0},t/30,0);
 const v=u*(1-Math.exp(-t/tau)),x=u*(t-tau*(1-Math.exp(-t/tau)));
 assert.ok(Math.abs(p.v.x-v)/v<.001);
 assert.ok(Math.abs(p.p.x-x)/x<.001);
 assert.equal(p.p.y,100);
});

test('Finite-Re drag converges toward independent fine-step RK4 displacement',()=>{
 // Independent RK4 of F=(rho_air Cd A/2)|u-v|(u-v), coupled gravity.
 // 100 micron mineral grain, 20 m/s carrier, 0.1 s. Reference supplied by
 // independent physics review, rather than generated by this integrator.
 const reference=1.54335439347,errors=[];
 for(const steps of [6,12,24]){
  const p=grain(100e-6);for(let i=0;i<steps;i++)advanceAerosol(p,{x:20,y:0,z:0},.1/steps);
  errors.push(Math.abs(p.p.x-reference));
 }
 assert.ok(errors[0]/reference<.045,'60 Hz displacement error stays below 4.5% in this finite-Re fixture');
 assert.ok(errors[1]<errors[0]*.52&&errors[2]<errors[1]*.52,'step halving must converge, not just stay finite');
 assert.ok(errors[2]/reference<.012);
 // At Re=1353.6 the high-Re Cd=.44 branch yields this rate in 1/s.
 assert.ok(Math.abs(dragRate(.001,2600,20)-3.1096153846153847)<1e-12);
});

test('Large slip and tiny response times remain finite and never overshoot carrier velocity without gravity',()=>{
 for(const d of [1e-6,5e-6,.0001,.0015,.005])for(const dt of [1/240,1/60,.1]){
  const p=grain(d);for(let i=0;i<100;i++)advanceAerosol(p,{x:1000,y:-800,z:600},dt,0);
  assert.ok([...Object.values(p.p),...Object.values(p.v)].every(Number.isFinite));
  assert.ok(p.v.x>=0&&p.v.x<=1000&&p.v.y<=0&&p.v.y>=-800&&p.v.z>=0&&p.v.z<=600);
 }
});

test('Shared wake air changes actual parcel transport and calm ground does not emit dust',()=>{
 const f=new DisasterField(()=>0),e=f.start('tornado',{intensity:100,radius:180,speed:0,duration:90});e.time=3;
 const a=new TornadoParticles(f,{dust:1,flecks:0,turbulence:false});a.update(0,e);
 const p=a.dust[0];Object.assign(p.p,{x:20,y:40,z:0});p.diameter=10e-6;p.v={x:0,y:0,z:0};
 f.registerAirModifier((_x,_y,_z,air)=>{air.wx=12;air.wy=8;air.wz=-4;});
 for(let i=0;i<30;i++)a.update(1/60,e);
 assert.ok(p.p.x>25.5&&p.p.y>43.5&&p.p.z<-1.8,'registered field modifiers must advect aerosol positions');
 const calm=new TornadoParticles(constantAir(0),{dust:128,flecks:0});for(let i=0;i<180;i++)calm.update(1/60,event);
 assert.equal(calm.snapshot().dust,0);assert.equal(calm.emitted,0);assert.ok(calm.sourceSamples>0);
});

test('Cloud spread conserves extinction area while the bounded pool expires, deposits, pauses and resets',()=>{
 const r=parcelRadius(3,.4,10),tau=parcelOpticalDepth(12,r);
 assert.ok(r>3);assert.ok(tau<parcelOpticalDepth(12,3));assert.ok(Math.abs(tau*Math.PI*r*r-12)<1e-12);
 const field=constantAir(20),a=new TornadoParticles(field,{dust:32,flecks:0});
 for(let i=0;i<1200;i++)a.update(1/60,event);
 assert.equal(a.all.length,32);assert.ok(a.emitted>32);assert.ok(a.expired>0);
 const live=a.dust.find(p=>p.active);live.p.y=-10;a.update(1/60,event);assert.ok(a.deposited>0);
 const before=JSON.stringify(a.all);field.paused=true;a.update(.1,event);assert.equal(JSON.stringify(a.all),before);
 a.clear();assert.equal(a.emitted,0);assert.equal(a.expired,0);assert.equal(a.deposited,0);assert.equal(a.snapshot().dust,0);
 field.paused=false;a.update(1/60,event);assert.ok(a.emitted>0);
});

test('Submitting particle geometry settles position, size and rotation history before a paused render',()=>{
 const f=new DisasterField(()=>0),e=f.start('tornado',{intensity:100,radius:180,speed:0,duration:90});e.time=3;
 const v=new TornadoVisuals({scene:new Scene(),camera:{position:new Vector3(0,50,120)},sceneRenderer:{opaqueCopy:{depthTexture:null}}},f);
 for(let i=0;i<60;i++)v.update(1/60);
 assert.ok(v.dust.geometry.instanceCount>20);
 const a=v.dust.geometry.attributes;
 assert.notDeepEqual(Array.from(a.previous.array.slice(0,3)),Array.from(a.parcel.array.slice(0,3)));
 v.settleMotion();
 for(let i=0;i<v.dust.geometry.instanceCount;i++){
  const o=i*4;assert.deepEqual(Array.from(a.previous.array.slice(o,o+3)),Array.from(a.parcel.array.slice(o,o+3)));
  assert.equal(a.previous.array[o+3],a.details.array[o+3]);assert.equal(a.motion.array[o+3],a.parcel.array[o+3]);
 }
 v.clear();assert.equal(v.dust.geometry.instanceCount,0);assert.equal(v.flecks.geometry.instanceCount,0);
});
